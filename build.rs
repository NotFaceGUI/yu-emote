//! Build script: index the committed WGSL files under `shaders/`.
//!
//! The shader sources are ordinary files so they can be reviewed and diffed
//! without running the generator. This script only emits a small lookup table
//! with compile-time `include_str!` calls; it does not compile or validate the
//! WGSL itself. `cargo run --bin gen-shaders` regenerates the files, and the
//! `shader_files_match_generator` test keeps them in sync with the feature
//! table in `src/render.rs`.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let shader_root = manifest.join("shaders");
    println!("cargo:rerun-if-changed=shaders");

    let mut pixel_arms = String::new();
    for (directory, model) in [("ps_2_0", "Ps2"), ("ps_3_0", "Ps3")] {
        for (index, path) in numbered_files(&shader_root.join(directory)) {
            pixel_arms.push_str(&format!(
                "        (ShaderModel::{model}, {index}) => Some(include_str!(\"{}\")),\n",
                include_path(&path)
            ));
        }
    }

    let vs2 = shader_root.join("vs_2_0");
    let basic = first_existing(&[vs2.join("00.wgsl"), shader_root.join("vs_3_0/00.wgsl")]);
    let offset = first_existing(&[vs2.join("01.wgsl")]);
    let scaled = first_existing(&[vs2.join("02.wgsl")]);

    let vertex_arms = format!(
        "        VertexProgram::Basic => {},\n\
         \x20       VertexProgram::ScreenOffset => {},\n\
         \x20       VertexProgram::ScreenOffsetScaled => {},\n",
        basic
            .as_ref()
            .map(|path| format!("include_str!(\"{}\")", include_path(path)))
            .unwrap_or_else(|| "\"\"".to_string()),
        offset
            .as_ref()
            .map(|path| format!("include_str!(\"{}\")", include_path(path)))
            .unwrap_or_else(|| "\"\"".to_string()),
        scaled
            .as_ref()
            .map(|path| format!("include_str!(\"{}\")", include_path(path)))
            .unwrap_or_else(|| "\"\"".to_string()),
    );

    let generated = format!(
        "// Generated by build.rs. Do not edit.\n\
         pub(crate) fn pixel_shader_source(\n\
         \x20   model: ShaderModel,\n\
         \x20   index: usize,\n\
         ) -> Option<&'static str> {{\n\
         \x20   match (model, index) {{\n\
         {pixel_arms}\
         \x20       _ => None,\n\
         \x20   }}\n\
         }}\n\n\
         pub(crate) fn vertex_shader_source(program: VertexProgram) -> &'static str {{\n\
         \x20   match program {{\n\
         {vertex_arms}\
         \x20   }}\n\
         }}\n"
    );

    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("shader_index.rs");
    fs::write(&out, generated).expect("write shader index");
}

/// Numeric `.wgsl` files in `directory`, sorted by index.
fn numbered_files(directory: &Path) -> Vec<(usize, PathBuf)> {
    let Ok(entries) = fs::read_dir(directory) else {
        return Vec::new();
    };
    let mut files = Vec::new();
    for entry in entries.flatten() {
        let path = entry.path();
        if path.extension().and_then(|ext| ext.to_str()) != Some("wgsl") {
            continue;
        }
        let Some(stem) = path.file_stem().and_then(|stem| stem.to_str()) else {
            continue;
        };
        let digits: String = stem.chars().take_while(char::is_ascii_digit).collect();
        let Ok(index) = digits.parse::<usize>() else {
            continue;
        };
        files.push((index, path));
    }
    files.sort_by_key(|(index, _)| *index);
    files
}

fn first_existing(paths: &[PathBuf]) -> Option<PathBuf> {
    paths.iter().find(|path| path.is_file()).cloned()
}

fn include_path(path: &Path) -> String {
    path.display().to_string().replace('\\', "/")
}
